def svg(w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{escape(title)}">'
            f'<title>{escape(title)}</title><style>{CSS}</style><rect class="bg" width="{w}" height="{h}" rx="10"/>{body}</svg>')


def width_of(s, mono=True):
    return int(len(s) * (7.3 if mono else 6.6)) + 22


def box(x, y, label, cls="box", sub=None, w=None):
    w = w or width_of(label)
    t = f'<rect class="{cls}" x="{x}" y="{y}" width="{w}" height="30" rx="6"/><text class="mono" x="{x + 11}" y="{y + 19}">{escape(label)}</text>'
    return t, w


def curve(x1, y1, x2, y2, cls):
    mx = (x1 + x2) / 2
    return f'<path class="{cls}" d="M{x1} {y1} C{mx} {y1} {mx} {y2} {x2} {y2}"/>'


def load(repo):
    g = json.loads((Path(repo) / ".agent-knowledge" / "graph.json").read_text(encoding="utf-8"))
    return {n["id"]: n for n in g["nodes"]}, g["edges"]


def short(i):
    return i.split(":", 1)[1].rsplit(".", 1)[-1] if i.startswith("type:") else i.split(":", 1)[1].split("#")[-1]


def is_test(n):
    f = n.get("file") or ""
    return n.get("role") == "test" or "/test" in f or f.startswith("t/") or ".test." in f or ".spec." in f or "/tests/" in f


def hierarchy(repo, root, name, title):
    nodes, edges = load(repo)
    rid = next(i for i in nodes if i.startswith("type:") and i.split(".")[-1] == root and nodes[i].get("kind_of") != "module")
    kids = defaultdict(list)
    for e in edges:
        if e["predicate"] in ("extends", "implements") and not is_test(nodes[e["from"]]):
            kids[e["to"]].append(e["from"])
    for k in kids:
        kids[k].sort()
    pos, order = {}, []

    def layout(n, d):
        if not kids.get(n):
            pos[n] = [d, len(order)]
            order.append(n)
        else:
            for c in kids[n]:
                layout(c, d + 1)
            ys = [pos[c][1] for c in kids[n]]
            pos[n] = [d, (min(ys) + max(ys)) / 2]

    layout(rid, 0)
    depth = max(p[0] for p in pos.values())
    colw = {d: max(width_of(short(n)) for n, p in pos.items() if p[0] == d) for d in range(depth + 1)}
    xs, x = {}, 24
    for d in range(depth + 1):
        xs[d] = x
        x += colw[d] + 46
    rowh = 40
    body = [f'<text class="h" x="24" y="26">{escape(title)}</text>']
    shapes = []
    for n, (d, y) in pos.items():
        cy = 48 + y * rowh
        for c in kids.get(n, []):
            d2, y2 = pos[c]
            shapes.append(curve(xs[d] + colw[d], cy + 15, xs[d2], 48 + y2 * rowh + 15, "hi"))
        b, _ = box(xs[d], cy, short(n), "root" if n == rid else "box", w=colw[d])
        shapes.append(b)
    h = 48 + (len(order)) * rowh + 34
    body += shapes
    body.append(f'<text class="mut" x="24" y="{h - 14}">{len(pos) - 1} subclasses at any depth. Solid lines are [high] edges. Generated by `kg subclasses {root}`.</text>')
    (OUT / name).write_text(svg(max(x, 560), h, "".join(body), title), encoding="utf-8")


def fanin(repo, target, name, title):
    nodes, edges = load(repo)
    tid = next(i for i in nodes if i.startswith("method:") and i.endswith("#" + target))
    src = sorted({(e["from"], e["confidence"]) for e in edges if e["to"] == tid and e["predicate"] == "calls" and not is_test(nodes[e["from"]])})
    labels = []
    for f, c in src:
        owner = f.split(":", 1)[1].split("#")[0].split(".")
        labels.append((f"{owner[-1]}#{f.split('#')[1]}" if f.split("#")[1] != "render" else owner[-1], c, nodes[f].get("file", "")))
    cw = max(width_of(l[0]) for l in labels)
    tw = width_of(target)
    x2 = 24 + cw + 120
    rowh = 40
    h = 52 + len(labels) * rowh + 40
    body = [f'<text class="h" x="24" y="26">{escape(title)}</text>']
    ty = 48 + (len(labels) - 1) * rowh / 2
    for i, (lab, conf, file) in enumerate(labels):
        y = 48 + i * rowh
        b, _ = box(24, y, lab, w=cw)
        body.append(b)
        body.append(curve(24 + cw, y + 15, x2, ty + 15, "med" if conf == "medium" else "hi"))
        body.append(f'<text class="mut" x="{x2 + tw + 30}" y="{y + 19}">{escape(file.rsplit("/", 1)[-1] if i < 0 else "")}</text>')
    b, _ = box(x2, ty, target, "root", w=tw)
    body.append(b)
    body.append(f'<text class="mut" x="24" y="{h - 14}">Dashed amber = [medium]: call resolved by a fixed rule. Made with `kg callers {target}`.</text>')
    (OUT / name).write_text(svg(max(x2 + tw + 40, 640), h, "".join(body), title), encoding="utf-8")


def routes(repo, repo_type, name, title):
    nodes, edges = load(repo)
    rid = next(i for i in nodes if i.startswith("type:") and i.endswith("." + repo_type))
    ctrls = sorted({e["from"] for e in edges if e["to"] == rid and e["predicate"] == "depends_on"})
    rows = []
    for c in ctrls:
        ms = {e["to"] for e in edges if e["from"] == c and e["predicate"] == "has_method"}
        rs = sorted(e["from"] for e in edges if e["predicate"] == "handled_by" and e["to"] in ms)
        if rs:
            rows.append((c, rs))
    rows = [(c, rs[:5], len(rs)) for c, rs in rows if "Controller" in c]
    colr = max(width_of(r.split(":", 1)[1]) for _, rs, _ in rows for r in rs)
    colc = max(width_of(short(c)) for c, _, _ in rows)
    rowh = 38
    x1, x2, x3 = 24, 24 + colr + 70, 24 + colr + 70 + colc + 70
    ys, cur, body = [], 48, [f'<text class="h" x="24" y="26">{escape(title)}</text>']
    cy_list = []
    for c, rs, total in rows:
        start = cur
        for r in rs:
            b, _ = box(x1, cur, r.split(":", 1)[1], w=colr)
            body.append(b)
            cur += rowh
        mid = start + (cur - rowh - start) / 2
        cy_list.append((c, mid, start, rs, total))
        cur += 14
    h = cur + 34
    rep_y = (cy_list[0][1] + cy_list[-1][1]) / 2
    for c, mid, start, rs, total in cy_list:
        b, _ = box(x2, mid, short(c), w=colc)
        body.append(b)
        for k in range(len(rs)):
            body.append(curve(x1 + colr, start + k * rowh + 15, x2, mid + 15, "hi"))
        body.append(curve(x2 + colc, mid + 15, x3, rep_y + 15, "hi"))
        if total > len(rs):
            body.append(f'<text class="mut" x="{x1}" y="{start + len(rs) * rowh - 6}"></text>')
    b, _ = box(x3, rep_y, repo_type, "root", w=width_of(repo_type))
    body.append(b)
    body.append(f'<text class="mut" x="24" y="{h - 14}">HTTP routes (up to five per controller shown) to the controllers that handle them to the repository they use. All [high].</text>')
    (OUT / name).write_text(svg(x3 + width_of(repo_type) + 24, h, "".join(body), title), encoding="utf-8")


def pipeline():
    steps = [("Source files", "Java  Python  TS / JS"), ("Extractors", "tree-sitter, Python ast"), ("Claims", "one fact per line,\nfile + line + tag"), ("Graph", "graph.json"), ("For agents", "kg command\nmarkdown notes\nAGENTS.md block")]
    w, gap, bw = 1000, 34, 156
    body = []
    for i, (t, s) in enumerate(steps):
        x = 24 + i * (bw + gap)
        body.append(f'<rect class="{"root" if i == 2 else "box"}" x="{x}" y="34" width="{bw}" height="92" rx="8"/><text x="{x + 14}" y="62" style="font-weight:600">{escape(t)}</text>')
        for j, line in enumerate(s.split("\n")):
            body.append(f'<text class="mut" x="{x + 14}" y="{84 + j * 17}">{escape(line)}</text>')
        if i:
            body.append(f'<path class="hi" d="M{x - gap + 4} 80 L{x - 5} 80"/><path class="hi" d="M{x - 11} 74 L{x - 5} 80 L{x - 11} 86"/>')
    body.append('<text class="mut" x="24" y="156">No language model is involved. The same source always produces the same claims.</text>')
    (OUT / "pipeline.svg").write_text(svg(w, 176, "".join(body), "How the graph is built"), encoding="utf-8")


def results():
    rows = [("Java, large repo (Codex)", 42, None), ("Small Python/TS repos", 92, 117), ("Large Python/TS repos", 110, 116), ("Multi-hop questions", 104, 127), ("With kg subclasses", 105, 85)]
    body = [f'<text class="h" x="24" y="26">Tokens per question with the graph, as a % of no graph (lower is better)</text>']
    x0, scale, rowh = 230, 2.4, 52
    body.append(f'<text class="mut" x="{x0 + 100 * scale - 40}" y="48">100% = no graph</text>')
    for i, (label, c, x) in enumerate(rows):
        y = 62 + i * rowh
        body.append(f'<text x="24" y="{y + 20}">{escape(label)}</text>')
        body.append(f'<rect x="{x0}" y="{y}" width="{c * scale}" height="16" rx="3" fill="var(--acc)"/><text class="mono" x="{x0 + c * scale + 8}" y="{y + 13}">{c}%{" Claude Code" if x else ""}</text>')
        if x:
            body.append(f'<rect x="{x0}" y="{y + 20}" width="{x * scale}" height="16" rx="3" fill="var(--med)"/><text class="mono" x="{x0 + x * scale + 8}" y="{y + 33}">{x}% Codex</text>')
    h = 62 + len(rows) * rowh + 30
    body.append(f'<line x1="{x0 + 100 * scale}" y1="54" x2="{x0 + 100 * scale}" y2="{h - 36}" stroke="var(--mut)" stroke-dasharray="3 3"/>')
    body.append(f'<text class="mut" x="24" y="{h - 12}">Answers were correct in every arm. Java row: shopizer, 398k vs 953k tokens. Other rows: Claude Code and Codex, 2 to 4 runs per cell.</text>')
    (OUT / "results.svg").write_text(svg(880, h, "".join(body), "Token cost with the graph relative to no graph"), encoding="utf-8")


if __name__ == "__main__":
    pipeline()
    results()
    if len(sys.argv) >= 4:
        celery, nxt, pet = sys.argv[1:4]
        hierarchy(celery, "BaseKeyValueStoreBackend", "hierarchy-python.svg", "Python: every subclass of BaseKeyValueStoreBackend in Celery")
        fanin(nxt, "getI18nPath", "callers-typescript.svg", "TypeScript: who calls getI18nPath in Next-js-Boilerplate")
        routes(pet, "OwnerRepository", "routes-java.svg", "Java: routes, controllers and the repository in Spring Petclinic")
